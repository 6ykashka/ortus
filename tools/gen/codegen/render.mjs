// W0.09 · рендер Go-файлов кодогенерации. Вывод проходит gofmt в codegen.mjs (выравнивание, импорты).
const HEADER = '// Code generated by tools/gen/codegen.mjs. DO NOT EDIT.';
const MODULE = 'github.com/ortus/ortus-crm/backend';

/** Строковый литерал Go (JSON-экранирование совместимо с интерпретируемыми строками Go). */
const q = (s) => JSON.stringify(String(s));
const strings = (xs) => `[]string{${xs.map(q).join(', ')}}`;

function file(pkg, doc, body) {
  return [HEADER, `// Source: ${doc}.`, '', `package ${pkg}`, '', body.trimEnd(), ''].join('\n');
}

/** backend/internal/api/catalog/operations.gen.go — операции бандла для шлюза cmd/api. */
export function renderOperationsGo(ops) {
  const rows = ops.map(
    (o) =>
      `\t{ID: ${q(o.id)}, Tag: ${q(o.tag)}, Method: ${q(o.method)}, Path: ${q(o.path)}, ` +
      `Permissions: ${strings(o.permissions)}, PermissionsMode: ${q(o.permissionsMode)}, ` +
      `Scope: ${q(o.scope)}, Public: ${o.public}, Mutating: ${o.mutating}},`,
  );
  return file(
    'catalog',
    'api/dist/ortus.bundle.yaml',
    `
// Operation is one operation of the OpenAPI contract: what the gateway of cmd/api checks before the handler.
type Operation struct {
	ID              string   // operationId
	Tag             string   // first OpenAPI tag
	Method          string   // HTTP method, upper case
	Path            string   // path template, chi syntax ({param})
	Permissions     []string // x-permissions
	PermissionsMode string   // x-permissions-mode: all | any
	Scope           string   // x-scope
	Public          bool     // security: [] (x-public-capability), no session
	Mutating        bool     // not GET/HEAD/OPTIONS/TRACE: CSRF and read-only checks apply
}

// Operations lists every operation of the contract, sorted by path and method.
var Operations = []Operation{
${rows.join('\n')}
}
`,
  );
}

/** backend/internal/api/catalog/problems.gen.go — реестр Problem.code из api/errors.yaml. */
export function renderProblemsGo(problems) {
  const rows = problems.map((p) => `\t${q(p.code)}: {Status: ${p.status}, Title: ${q(p.title)}},`);
  return file(
    'catalog',
    'api/errors.yaml',
    `
// Problem is the HTTP status and title of a canonical Problem.code.
type Problem struct {
	Status int
	Title  string
}

// Problems maps every Problem.code of the contract (enum ProblemCode) to its status and title.
var Problems = map[string]Problem{
${rows.join('\n')}
}
`,
  );
}

/** backend/internal/api/catalog/permissions.gen.go — действия каталога прав, кроме platform. */
export function renderPermissionsGo(actions) {
  return file(
    'catalog',
    'api/permissions.yaml',
    `
// TenantActions lists every tenant action of the permission catalog (all modules except platform), sorted.
// Owner template: "all tenant actions except those blocked by the driver function" (role_templates.owner).
var TenantActions = []string{
${actions.map((a) => `\t${q(a)},`).join('\n')}
}
`,
  );
}

/** backend/cmd/api/router.go — монтирование strict server каждого тега; nil → 501 not_implemented. */
export function renderRouterGo(tags) {
  const imports = [...tags]
    .sort((a, b) => (a.pkg < b.pkg ? -1 : 1))
    .map((t) => `\t${t.alias} ${q(`${MODULE}/internal/api/${t.pkg}`)}`);
  const fields = tags.map((t) => `\t${t.field} ${t.alias}.StrictServerInterface`);
  const mounts = tags.map(
    (t) => `\tif s.${t.field} != nil {
		${t.alias}.HandlerWithOptions(${t.alias}.NewStrictHandlerWithOptions(s.${t.field}, nil, ${t.alias}.StrictHTTPServerOptions{
			RequestErrorHandlerFunc:  o.requestError,
			ResponseErrorHandlerFunc: o.responseError,
		}), ${t.alias}.ChiServerOptions{BaseRouter: r, ErrorHandlerFunc: o.requestError})
	} else {
		o.notImplemented(r, ${q(t.tag)})
	}`,
  );
  return [
    HEADER,
    '// Source: api/dist/ortus.bundle.yaml (tags).',
    '',
    'package main',
    '',
    'import (',
    '\t"github.com/go-chi/chi/v5"',
    '',
    ...imports,
    ')',
    '',
    '// Servers holds the strict-server implementation of every OpenAPI tag. A nil field mounts the tag',
    '// as 501 not_implemented (behind the same gateway).',
    'type Servers struct {',
    ...fields,
    '}',
    '',
    '// mountTags registers every operation of the contract on r.',
    'func mountTags(r chi.Router, s Servers, o mountOptions) {',
    ...mounts,
    '}',
    '',
  ].join('\n');
}
