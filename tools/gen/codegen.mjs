// Кодогенерация из контракта (W0.09, `make gen` ≡ `corepack pnpm run gen`).
//   node tools/gen/codegen.mjs
// Вход: api/dist/ortus.bundle.yaml (W0.07), api/errors.yaml, api/permissions.yaml. Выход (руками не править):
//   backend/internal/api/<tag>/<tag>.gen.go      oapi-codegen v2.8.0: модели, chi-сервер, strict server
//   backend/internal/api/catalog/*.gen.go         операции (шлюз cmd/api), коды ошибок, tenant actions
//   backend/cmd/api/router.go                     монтирование тегов (nil → 501 not_implemented)
//   frontend/packages/api-client/src/generated/schema.ts   openapi-typescript 7.13.0
// Дрейф проверяет CI W0.04 (`contract/codegen-drift`): повторный запуск не меняет файлов.
import { spawnSync } from 'node:child_process';
import { existsSync, mkdtempSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { pathToFileURL } from 'node:url';
import { oapiConfig, operationsOf, problemsOf, tagsOf, tenantActionsOf } from './codegen/model.mjs';
import {
  renderOperationsGo,
  renderPermissionsGo,
  renderProblemsGo,
  renderRouterGo,
} from './codegen/render.mjs';
import { abs, BUNDLE_PATH, ERRORS_PATH, PERMISSIONS_PATH, ROOT } from './lib/paths.mjs';
import { format, readYaml, writeText } from './lib/yaml-io.mjs';

/** Версия генератора Go закреплена здесь: `go install …@<версия>` во временный каталог, go.mod не трогается. */
export const OAPI_CODEGEN = 'github.com/oapi-codegen/oapi-codegen/v2/cmd/oapi-codegen@v2.8.0';
const API_DIR = 'backend/internal/api';
const CATALOG_DIR = `${API_DIR}/catalog`;
const ROUTER_FILE = 'backend/cmd/api/router.go';
const TS_SCHEMA = 'frontend/packages/api-client/src/generated/schema.ts';
const EXE = process.platform === 'win32' ? '.exe' : '';

function run(cmd, args, opts = {}) {
  const r = spawnSync(cmd, args, { cwd: ROOT, encoding: 'utf8', ...opts });
  if (r.error) throw new Error(`${cmd}: ${r.error.message}`);
  if (r.status !== 0) {
    throw new Error(`${cmd} ${args.join(' ')} → exit ${r.status}\n${r.stderr || r.stdout}`);
  }
  return r.stdout;
}

const gofmt = (src) => run('gofmt', [], { input: src });

function installOapiCodegen(tmp) {
  run('go', ['install', OAPI_CODEGEN], { env: { ...process.env, GOBIN: tmp } });
  return join(tmp, `oapi-codegen${EXE}`);
}

/** Удаляет каталоги backend/internal/api/<x>, которых больше нет среди тегов (контракт аддитивен, но мало ли). */
function pruneStale(tags) {
  const keep = new Set([...tags.map((t) => t.pkg), 'catalog']);
  for (const e of readdirSync(abs(API_DIR), { withFileTypes: true })) {
    if (e.isDirectory() && !keep.has(e.name))
      rmSync(abs(`${API_DIR}/${e.name}`), { recursive: true });
  }
}

function generateGoTags(tags, tmp) {
  const bin = installOapiCodegen(tmp);
  for (const t of tags) {
    const cfg = join(tmp, `${t.pkg}.yaml`);
    writeFileSync(cfg, oapiConfig(t), 'utf8');
    writeText(abs(t.file), ''); // каталог тега должен существовать
    run(bin, ['-config', cfg, BUNDLE_PATH]);
  }
}

async function generateTs() {
  // devDependency @ortus/api-client (pnpm кладёт ссылку в node_modules пакета); пакет — только ESM.
  const dir = abs('frontend/packages/api-client/node_modules/openapi-typescript');
  const entry = JSON.parse(readFileSync(join(dir, 'package.json'), 'utf8')).exports['.'].import;
  const mod = await import(pathToFileURL(join(dir, entry)).href);
  const ast = await mod.default(pathToFileURL(BUNDLE_PATH));
  const header =
    '// Code generated by tools/gen/codegen.mjs (openapi-typescript) from api/dist/ortus.bundle.yaml. DO NOT EDIT.\n';
  writeText(abs(TS_SCHEMA), await format(header + mod.astToString(ast), abs(TS_SCHEMA)));
}

export async function generate() {
  const bundle = readYaml(BUNDLE_PATH);
  const tags = tagsOf(bundle);
  if (!existsSync(abs(API_DIR))) writeText(abs(`${CATALOG_DIR}/.keep`), '');
  pruneStale(tags);

  const tmp = mkdtempSync(join(tmpdir(), 'ortus-gen-'));
  try {
    generateGoTags(tags, tmp);
  } finally {
    rmSync(tmp, { recursive: true, force: true });
  }
  rmSync(abs(`${CATALOG_DIR}/.keep`), { force: true });

  const files = [
    [`${CATALOG_DIR}/operations.gen.go`, renderOperationsGo(operationsOf(bundle))],
    [`${CATALOG_DIR}/problems.gen.go`, renderProblemsGo(problemsOf(readYaml(ERRORS_PATH)))],
    [
      `${CATALOG_DIR}/permissions.gen.go`,
      renderPermissionsGo(tenantActionsOf(readYaml(PERMISSIONS_PATH))),
    ],
    [ROUTER_FILE, renderRouterGo(tags)],
  ];
  for (const [path, src] of files) writeText(abs(path), gofmt(src));
  await generateTs();
  return { tags: tags.length, files: files.length + tags.length + 1 };
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) {
  try {
    const r = await generate();
    console.log(
      `gen: ${r.tags} тегов → backend/internal/api, catalog, router.go, api-client — ${r.files} файлов`,
    );
  } catch (e) {
    console.error(`gen: ${e.message}`);
    process.exit(1);
  }
}
