import { describe, expect, it } from 'vitest';

import { dm, kTxt, plw, rub, signed, unitLabel } from './format.ts';

describe('rub: рубли из копеек, пробел разрядов, знак ₽', () => {
  it.each([
    [43_817_500, '438 175 ₽'],
    [0, '0 ₽'],
    [150, '2 ₽'],
    [149, '1 ₽'],
    [-9_000_00, '−9 000 ₽'],
  ])('%d → %s', (minor, s) => {
    expect(rub(minor)).toBe(s);
  });
});

describe('signed: разница со знаком (sgn эталона :1430)', () => {
  it.each([
    [1_305_000, '+13 050 ₽'],
    [-1_305_000, '−13 050 ₽'],
    [0, '0 ₽'],
    [40, '0 ₽'],
    [60, '+1 ₽'],
  ])('%d → %s', (minor, s) => {
    expect(signed(minor)).toBe(s);
  });
});

describe('plw: русские множественные формы', () => {
  it.each([
    [1, 'раздел'],
    [2, 'раздела'],
    [4, 'раздела'],
    [5, 'разделов'],
    [11, 'разделов'],
    [12, 'разделов'],
    [21, 'раздел'],
    [22, 'раздела'],
    [100, 'разделов'],
    [101, 'раздел'],
  ])('%d → %s', (n, w) => {
    expect(plw(n, 'раздел', 'раздела', 'разделов')).toBe(w);
  });
});

describe('dm: день и месяц по Москве', () => {
  it('ISO-момент → ДД.ММ', () => {
    expect(dm('2026-09-29T08:00:00Z')).toBe('29.09');
    expect(dm('2026-09-29T22:30:00Z')).toBe('30.09');
  });
  it('нет даты — тире', () => {
    expect(dm(undefined)).toBe('—');
  });
});

describe('kTxt и unitLabel', () => {
  it('коэффициент: 1 и пусто — без добавки, прочее — « × k» с запятой', () => {
    expect(kTxt(undefined)).toBe('');
    expect(kTxt('1')).toBe('');
    expect(kTxt('1.07')).toBe(' × 1,07');
  });
  it('единицы контракта → подписи эталона', () => {
    expect(
      (['m2', 'm', 'm3', 'piece', 'set', 'trip', 'mesh', 'liter', 'hour'] as const).map(unitLabel),
    ).toEqual(['м²', 'м', 'м³', 'шт', 'компл', 'рейс', 'меш', 'л', 'ч']);
  });
});
