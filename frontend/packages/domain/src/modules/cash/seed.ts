function grantRole(
  roles: Role[],
  id: string,
  verbs: NonNullable<Role['actions']['cash']>,
  opt: Partial<CashOpts>,
): void {
  const r = roles.find((x) => x.id === id);
  if (r && !r.actions.cash) {
    r.actions = { ...r.actions, cash: verbs };
    r.cash = { ...CASH_OPT0, ...opt };
  }
}

