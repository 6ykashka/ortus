// W6.23 · Возврат 1: строка «Уведомим…» дословно по эталону (:1000): «Уведомим: <исполнители>; заказчика <имя в
// винительном падеже> — меняется дата сдачи.» Сервер (previewScheduleChange.notifyWho) называет заказчика словом «Заказчик».
import { describe, expect, it } from 'vitest';

import { accusativeName, notifyText } from './notify.ts';

describe('accusativeName: имя заказчика в винительном падеже (Q-W6.23-8)', () => {
  it.each([
    ['Ольга Смирнова', 'Ольгу Смирнову'],
    ['Мария Кузнецова', 'Марию Кузнецову'],
    ['Андрей Кузнецов', 'Андрея Кузнецова'],
    ['Пётр Фомин', 'Петра Фомина'],
    ['Илья Орлов', 'Илью Орлова'],
    ['Анна Шевченко', 'Анну Шевченко'],
  ])('%s → %s', (name, expected) => {
    expect(accusativeName(name)).toBe(expected);
  });

  it('неузнаваемое имя и пустая строка остаются как есть', () => {
    expect(accusativeName('ООО «Ромашка»')).toBe('ООО «Ромашка»');
    expect(accusativeName('')).toBe('');
  });
});

describe('notifyText: «Уведомим: …»', () => {
  it('исполнители и заказчик, если меняется дата сдачи', () => {
    expect(
      notifyText(['Бригада О. Дронова', 'Алексей Соколов', 'Заказчик'], 'Ольга Смирнова'),
    ).toBe(
      'Уведомим: Бригада О. Дронова, Алексей Соколов; заказчика Ольгу Смирнову — меняется дата сдачи.',
    );
  });

  it('без заказчика в списке — точка после исполнителей', () => {
    expect(notifyText(['Бригада О. Дронова'], 'Ольга Смирнова')).toBe(
      'Уведомим: Бригада О. Дронова.',
    );
  });

  it('исполнителей нет', () => {
    expect(notifyText([], 'Ольга Смирнова')).toBe('Уведомим: исполнителей нет.');
    expect(notifyText(['Заказчик'], '')).toBe(
      'Уведомим: исполнителей нет; заказчика — меняется дата сдачи.',
    );
  });
});
