// Ссылки ячеек, диапазоны и список функций (documents.js 19.10:237–257).
// Столбцы A–Z (26), строки с 1; «$» в ссылке игнорируется.
import type { CellRef } from './types.ts';

const COLS = 'ABCDEFGHIJKLMNOPQRSTUVWXYZ';

export const colName = (i: number): string => COLS[i] ?? '?';

export function parseKey(k: unknown): CellRef | null {
  const m = /^\$?([A-Z])\$?(\d+)$/.exec(String(k ?? '').toUpperCase());
  return m ? { c: COLS.indexOf(m[1] ?? ''), r: Number(m[2]) } : null;
}

export const keyOf = (c: number, r: number): string => (COLS[c] ?? '') + r;

export function rangeKeys(a: string, b?: string): string[] {
  const x = parseKey(a);
  const y = parseKey(b || a);
  if (!x || !y) return [];
  const out: string[] = [];
  for (let r = Math.min(x.r, y.r); r <= Math.max(x.r, y.r); r++) {
    for (let c = Math.min(x.c, y.c); c <= Math.max(x.c, y.c); c++) out.push(keyOf(c, r));
  }
  return out;
}

export function inRange(key: string, range: string): boolean {
  const [a, b] = String(range).split(':');
  const p = parseKey(key);
  const x = parseKey(a);
  const y = parseKey(b || a);
  if (!p || !x || !y) return false;
  return (
    p.c >= Math.min(x.c, y.c) &&
    p.c <= Math.max(x.c, y.c) &&
    p.r >= Math.min(x.r, y.r) &&
    p.r <= Math.max(x.r, y.r)
  );
}

